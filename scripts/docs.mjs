// Generate references from the same schemas that drive the application UI.
import { build } from 'esbuild';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'synapse-docs-'));
try {
  const outfile = path.join(temp, 'models.mjs');
  await build({ stdin: { contents: `export { SETTINGS, defaultConfig, emitConfigToml } from './src/shared/settings'; export { ACTIONS } from './src/shared/keybindings'; export { checkExtensionManifest, PresetSchema } from './src/shared/manifest'; export { ThemeFileSchema } from './src/shared/theme';`, resolveDir: process.cwd() }, bundle: true, platform: 'node', format: 'esm', outfile });
  const m = await import(pathToFileURL(outfile));
  const escape = v => String(v).replaceAll('|', '\\|').replaceAll('\n', ' ');
  const lines = ['# Settings reference', '', 'Generated by `npm run docs:generate` from the runtime settings registry. Restart-required fields are marked.', '', '| Key | Default | Description |', '| --- | --- | --- |'];
  for (const s of m.SETTINGS) lines.push(`| ${s.key} | ${escape(JSON.stringify(s.default))} | ${escape(s.description)}${s.restart ? ' **Restart required.**' : ''} |`);
  fs.writeFileSync('docs/SETTINGS.md', lines.join('\n') + '\n');
  fs.writeFileSync('docs/KEYBINDINGS.md', '# Keybindings\n\nGenerated from the action registry. Settings → Keybindings edits these bindings; an empty accelerator disables an action. Conflicts are reported.\n\n| Action | Shortcut |\n| --- | --- |\n' + m.ACTIONS.map(a => `| ${a.label} (${a.id}) | ${a.default} |`).join('\n') + '\n');
  fs.writeFileSync('examples/config.toml', m.emitConfigToml(m.defaultConfig()));
  for (const dir of fs.readdirSync('examples', { withFileTypes: true }).filter(d => d.isDirectory())) {
    const base = path.join('examples', dir.name);
    const manifest = JSON.parse(fs.readFileSync(path.join(base, 'manifest.json')));
    const check = m.checkExtensionManifest(manifest);
    if (!check.ok) throw new Error(`${dir.name}: ${check.errors.join('; ')}`);
    for (const name of manifest.themes ?? []) {
      // TOML parser is bundled below to avoid an ad-hoc validation path.
      const { parse } = await import('smol-toml');
      m.ThemeFileSchema.parse(parse(fs.readFileSync(path.join(base, name), 'utf8')));
    }
  }
  console.log(`Generated ${m.SETTINGS.length} settings and ${m.ACTIONS.length} bindings; all example manifests/themes validate.`);
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
